package pool

import (
	"fmt"
	"path/filepath"
)

// dispatcherTemplate is the §5.3 dispatcher script (normative — pinned
// verbatim from design/harness/unified-harness-pool.md §5.3, byte for byte
// aside from the "%s" substitution for the harness name). It may use only sh
// builtins, uname, and cat — no bashisms — so it runs on debian, alpine/
// busybox, and the Guix FHS container. GenerateDispatcher's golden-file test
// (dispatcher_test.go) pins the fully rendered output independently, so any
// accidental edit here shows up as a deliberate, reviewed diff rather than a
// silent behavior change.
const dispatcherTemplate = `#!/bin/sh
# generated by wraptool — do not edit
set -eu
name=%s
root=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)   # .../runtime
m=$(uname -m)
case "$m" in
  x86_64)          arch=amd64 ;;
  aarch64|arm64)   arch=arm64 ;;
  *) echo "wraptool: unsupported architecture $m for $name" >&2; exit 69 ;;
esac
libc=glibc
[ -e "/lib/ld-musl-$m.so.1" ] && libc=musl
key=${WRAPTOOL_PLATFORM:-linux-$arch-$libc}
ptr="$root/active/$key/$name.gen"
if [ ! -f "$ptr" ]; then
  echo "wraptool: $name is not realized for $key;" >&2
  echo "run on the host: wraptool harness sync --platform $key" >&2
  exit 69
fi
gen=$(cat "$ptr")
exec "$root/generations/$gen/bin/$name" "$@"
`

// GenerateDispatcher returns the generated runtime/bin/<harnessName>
// dispatcher script content for harnessName (§5.3). It performs no
// validation of harnessName itself (that is WriteDispatcher's job, since
// this function's signature is pinned to return only the bytes) — every
// production caller reaches this only through WriteDispatcher or
// ActivateGeneration, both of which validate first.
func GenerateDispatcher(harnessName string) []byte {
	return []byte(fmt.Sprintf(dispatcherTemplate, harnessName))
}

// runtimeBinDir and runtimeBinFile mirror layout.go's Root()-rooted
// RuntimeBinDir/RuntimeBinFile, parameterized on an explicit runtime root
// instead of calling Root() directly — the same reasoning as realize.go's
// runtimeGenerationsDir/runtimeGenerationDir: production wiring passes
// pool.RuntimeDir() (via PoolPaths.Runtime), tests pass a t.TempDir()
// subdirectory.
func runtimeBinDir(runtimeRoot string) string {
	return filepath.Join(runtimeRoot, "bin")
}

func runtimeBinFile(runtimeRoot, harnessName string) string {
	return filepath.Join(runtimeBinDir(runtimeRoot), harnessName)
}

// WriteDispatcher generates and atomically writes runtime/bin/<harnessName>
// (§5.3), 0o755 so a project container can exec it directly. harnessName is
// validated as a single path segment first (validatePathSegment, the same
// rule GenerationID's harness/version inputs already follow) since it is
// interpolated directly into shell source with no further escaping, and
// becomes the dispatcher's own file name under runtime/bin/.
//
// Called by ActivateGeneration on every activation (§5.3: "regenerated, not
// edited, on every activation") — the dispatcher's content never varies by
// generation id, only by harness name, so repeated calls for the same
// harness simply rewrite identical bytes.
func WriteDispatcher(paths PoolPaths, harnessName string) error {
	if err := validatePathSegment("harness", harnessName); err != nil {
		return fmt.Errorf("writing dispatcher for %s: %w", harnessName, err)
	}
	data := GenerateDispatcher(harnessName)
	if err := WriteFileAtomic(runtimeBinFile(paths.Runtime, harnessName), data, 0o755); err != nil {
		return fmt.Errorf("writing dispatcher for %s: %w", harnessName, err)
	}
	return nil
}
